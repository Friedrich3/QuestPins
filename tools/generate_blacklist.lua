-- Generates Data/Blacklist.lua from Questie's quest blacklist, evaluated for WoW Forever.
--
-- Forever uses Era (Classic) content, so the blacklist is evaluated with
-- Expansions.Current = Era and every season/region flag off, exactly as Questie does on Forever.
-- Any truthy value (true or "HIDE_ON_MAP") hides the quest on the map.
--
-- Usage (Lua 5.1):
--   lua5.1 tools/generate_blacklist.lua <path-to-Questie-checkout> > Data/Blacklist.lua

local questiePath = assert(arg[1], "usage: generate_blacklist.lua <Questie checkout> [questie revision]")
local revision = arg[2] or "unknown"

local modules = {}
local Expansions = { Era = 1, Tbc = 2, Wotlk = 3, Cata = 4, MoP = 5 }
Expansions.Current = Expansions.Era
modules.Expansions = Expansions
modules.ContentPhases = setmetatable({ activePhases = {} }, {
    __index = function() return function(list) return list end end,
})

_G.QuestieLoader = {
    CreateModule = function(_, name) modules[name] = modules[name] or {}; return modules[name] end,
    ImportModule = function(_, name) modules[name] = modules[name] or {}; return modules[name] end,
}
_G.Questie = setmetatable({ Debug = function() end }, { __index = function() return false end })

local chunk = assert(loadfile(questiePath .. "/Database/Corrections/QuestieQuestBlacklist.lua"))
chunk()

local Blacklist = modules.QuestieQuestBlacklist
local hidden = {}
for questId, flag in pairs(Blacklist:Load()) do
    if flag then hidden[questId] = true end
end
-- Questie hides these by default too: AQ War Effort turn-ins (incl. Commendation Signets;
-- option off by default) and Naxxramas invasion quests (only active on Season of Discovery).
local extra = 0
for _, list in ipairs({ Blacklist.AQWarEffortQuests or {}, Blacklist.InvasionQuests or {} }) do
    for questId, flag in pairs(list) do
        if flag and not hidden[questId] then
            hidden[questId] = true
            extra = extra + 1
        end
    end
end
local ids = {}
for questId in pairs(hidden) do ids[#ids + 1] = questId end
table.sort(ids)
io.stderr:write(("AQ war effort / invasion additions: %d\n"):format(extra))

local out = {}
out[#out + 1] = "-- GENERATED by tools/generate_blacklist.lua - do not edit by hand."
out[#out + 1] = "-- Source: Questie (https://github.com/Questie/Questie) revision " .. revision .. ","
out[#out + 1] = "-- Database/Corrections/QuestieQuestBlacklist.lua evaluated for Forever (Era content),"
out[#out + 1] = "-- plus its AQ War Effort and invasion lists, which Questie also hides by default."
out[#out + 1] = "-- Licensed GPL-3.0 like the source it is derived from."
out[#out + 1] = "local _, ns = ..."
out[#out + 1] = "ns.Blacklist = {"
local line = {}
for i, id in ipairs(ids) do
    line[#line + 1] = "[" .. id .. "]=true,"
    if #line == 10 or i == #ids then
        out[#out + 1] = "    " .. table.concat(line, " ")
        line = {}
    end
end
out[#out + 1] = "}"
io.write(table.concat(out, "\n"), "\n")
io.stderr:write(("blacklisted quests: %d\n"):format(#ids))
